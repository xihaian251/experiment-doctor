"""``experiment.lock.json`` schema (v1 Phase 1).

Every leaf is a v0.1 ``ProvenanceField``: value + evidence grade + source.  The
UNKNOWN discipline is enforced by the reused v0.1 validator (UNKNOWN never
carries a value; CONFIRMED/SUPPORTED always cite a source), so a lock can never
store a fabricated fact even by construction.

Field-level design and its evidence anchors:
``docs/v1/EXPERIMENT_DOCTOR_V1_IMPLEMENTATION_PLAN.md`` section 4.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from collections.abc import Iterator
from typing import Any

from pydantic import BaseModel, Field

from experiment_doctor.provenance import ProvenanceField, ProvenanceStatus, SourceRef

SCHEMA_VERSION = "1.0"


def _unknown(name: str) -> ProvenanceField[Any]:
    return ProvenanceField(
        value=None,
        status=ProvenanceStatus.UNKNOWN,
        confidence_note=f"{name}: not captured at init time",
    )


class IdentityBlock(BaseModel):
    experiment_id: ProvenanceField[str] = Field(
        default_factory=lambda: ProvenanceField.of(
            "exp-" + uuid.uuid4().hex,
            ProvenanceStatus.CONFIRMED,
            SourceRef(note="generated by lock writer"),
        )
    )
    created_at: ProvenanceField[str] = _unknown("identity.created_at")


class CodeBlock(BaseModel):
    repository: ProvenanceField[str] = _unknown("code.repository")
    commit: ProvenanceField[str] = _unknown("code.commit")
    dirty: ProvenanceField[bool] = _unknown("code.dirty")
    diff_hash: ProvenanceField[str] = _unknown("code.diff_hash")


class DatasetBlock(BaseModel):
    paths: ProvenanceField[list[str]] = _unknown("dataset.paths")
    fingerprints: ProvenanceField[dict[str, str]] = _unknown("dataset.fingerprints")


class ConfigurationBlock(BaseModel):
    config_files: ProvenanceField[list[str]] = _unknown("configuration.config_files")
    config_hash: ProvenanceField[dict[str, str]] = _unknown("configuration.config_hash")


class RandomnessBlock(BaseModel):
    seed: ProvenanceField[int] = _unknown("randomness.seed")
    seed_source: ProvenanceField[str] = _unknown("randomness.seed_source")


class EnvironmentBlock(BaseModel):
    python_version: ProvenanceField[str] = _unknown("environment.python_version")
    packages: ProvenanceField[dict[str, str]] = _unknown("environment.packages")
    platform: ProvenanceField[str] = _unknown("environment.platform")


class ExecutionBlock(BaseModel):
    command: ProvenanceField[str] = _unknown("execution.command")
    cwd: ProvenanceField[str] = _unknown("execution.cwd")
    start_time: ProvenanceField[str] = _unknown("execution.start_time")


class ArtifactsBlock(BaseModel):
    output_directory: ProvenanceField[str] = _unknown("artifacts.output_directory")


class ExperimentLock(BaseModel):
    """One lock per run; written at capture time, append-only thereafter.

    ``execution.start_time`` stays UNKNOWN in Phase 1: the run has not started
    (Phase 2's ``run`` wrapper fills it).  ``lock_hash`` covers the canonical
    serialization of every other block, so editing any value invalidates it.
    """

    schema_version: str = SCHEMA_VERSION
    identity: IdentityBlock = Field(default_factory=IdentityBlock)
    code: CodeBlock = Field(default_factory=CodeBlock)
    dataset: DatasetBlock = Field(default_factory=DatasetBlock)
    configuration: ConfigurationBlock = Field(default_factory=ConfigurationBlock)
    randomness: RandomnessBlock = Field(default_factory=RandomnessBlock)
    environment: EnvironmentBlock = Field(default_factory=EnvironmentBlock)
    execution: ExecutionBlock = Field(default_factory=ExecutionBlock)
    artifacts: ArtifactsBlock = Field(default_factory=ArtifactsBlock)
    lock_hash: str | None = None

    def body(self) -> dict[str, Any]:
        return self.model_dump(mode="json", exclude={"lock_hash"})

    def canonical_json(self) -> str:
        """Deterministic serialization: sorted keys, no whitespace, UTF-8 safe."""
        return json.dumps(self.body(), sort_keys=True, separators=(",", ":"), ensure_ascii=False)

    def compute_hash(self) -> str:
        return "sha256:" + hashlib.sha256(self.canonical_json().encode("utf-8")).hexdigest()

    def seal(self) -> ExperimentLock:
        """Return a copy whose ``lock_hash`` covers the canonical body."""
        return self.model_copy(update={"lock_hash": self.compute_hash()})

    def fields(self) -> Iterator[tuple[str, ProvenanceField[Any]]]:
        """Walk every evidence-graded leaf as (dotted.name, field)."""
        for block_name, block in (
            ("identity", self.identity),
            ("code", self.code),
            ("dataset", self.dataset),
            ("configuration", self.configuration),
            ("randomness", self.randomness),
            ("environment", self.environment),
            ("execution", self.execution),
            ("artifacts", self.artifacts),
        ):
            for field_name, field in vars(block).items():
                if isinstance(field, ProvenanceField):
                    yield f"{block_name}.{field_name}", field
